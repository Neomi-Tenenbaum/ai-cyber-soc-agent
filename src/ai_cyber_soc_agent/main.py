def call_security_model(state: AgentState):
    """Processes the active thread state, calculating reasoning behaviors or enforcing structural boundaries."""

    # Force create an HTTP client that completely ignores local network SSL verification
    custom_client = httpx.Client(verify=False)

    # Initialize the OpenAI model and BIND the tools directly to it
    base_model = ChatOpenAI(model="gpt-4o-mini", temperature=0, http_client=custom_client)
    model = base_model.bind_tools(SOC_TOOLS, parallel_tool_calls=False)
    
    # Compile the final system prompt context embedding runtime session metadata
    system_content = generate_dynamic_system_prompt(state)
    messages = [{"role": "system", "content": system_content}] + state["messages"]
    
    # Check if the user input string matches validation/compliance auditing reporting requests
    if len(state["messages"]) > 0 and "report" in state["messages"][-1].content.lower():
        # Morph the standard text response interface into a hardbound Pydantic schema validation pipeline
        structured_output_model = model.with_structured_output(TechnicalRiskReport)
        response = structured_output_model.invoke(messages)
        return {
            "structured_report": response.dict(), 
            "messages": [AIMessage(content="Security analysis completed. TechnicalRiskReport structured artifact compiled successfully.")]
        }
    
    # Fallback to general conversational chat or standard tool identification behavior
    response = model.invoke(messages)
    return {"messages": [response]}


def reject_tool_calls(state: AgentState):
    tool_messages = [
        ToolMessage(
            content="Action rejected by supervisor; it was not executed.",
            tool_call_id=call["id"],
        )
        for call in state["messages"][-1].tool_calls
    ]
    tool_messages.append(
        AIMessage(content="The requested action was not approved.")
    )
    return {"messages": tool_messages}


def evaluate_action_policy(state: AgentState) -> str:
    """
    Checks tool calls for destructive actions and requires human approval.

    Routing:
        - END: No tool calls or an unapproved action with no execution.
        - reject_tools: Adds rejection messages without executing the tools.
        - tools: Executes approved or non-destructive tool calls.
    """
    # Get the latest message generated by the model
    last_message = state["messages"][-1]

    # No tool calls means there is nothing to execute
    if not getattr(last_message, "tool_calls", None):
        return END

    # Inspect each requested tool call before execution
    for tool_call in last_message.tool_calls:
        # Require supervisor approval before isolating a server
        if (
            tool_call["name"] == "update_server_status"
            and tool_call["args"].get("status") == "isolated"
        ):
            decision = interrupt(
                {
                    "message": (
                        "Supervisor approval required to isolate "
                        f"server {tool_call['args'].get('ip')}."
                    ),
                    "allowed_actions": ["approve", "reject"],
                }
            )

            # Reject the action if approval is missing or invalid
            if (
                not isinstance(decision, dict)
                or decision.get("action") != "approve"
            ):
                return "reject_tools"

    # All requested tool calls are safe or explicitly approved
    return "tools"

def build_soc_workflow() -> StateGraph:
    """Builds and wires the internal structural routing state graph framework."""
    workflow = StateGraph(AgentState)
    
    # Initialize logical functional blocks inside the execution layout
    workflow.add_node("agent", call_security_model)
    workflow.add_node("tools", ToolNode(SOC_TOOLS, handle_tool_errors=True))
    workflow.add_node("reject_tools", reject_tool_calls)
    
    workflow.add_edge("reject_tools", END)
    # Map directional pathways and conditional routing decision points
    workflow.add_edge(START, "agent")
    workflow.add_conditional_edges("agent", evaluate_action_policy, {"tools": "tools", "reject_tools": "reject_tools", END: END})
    workflow.add_edge("tools", "agent")
    
    # Configure thread storage mechanisms to safely preserve step contexts
    runtime_memory = InMemorySaver()
    return workflow.compile(checkpointer=runtime_memory)

async def run_pipeline():
    """Run three SOC scenarios demonstrating different security behaviors."""

    # Initialize the global tracking set for this test run
    printed_ids = set()
    def _print_new_messages(step_output):
        """Filters and prints only new messages that have not been displayed yet."""
        if "messages" in step_output:
            for message in step_output["messages"]:
                # Check if the message has a unique ID and if it was already printed
                if getattr(message, "id", None) not in printed_ids:
                    message.pretty_print()
                    # Record the ID so it won't be printed in subsequent stream updates
                    if getattr(message, "id", None):
                        printed_ids.add(message.id)
    

    soc_application = build_soc_workflow()

    # Reset the database to baseline test data before running scenarios
    reset_test_data()  
    # clean the agent storage
    soc_application.checkpointer.storage.clear()

    # ============================================================
    # CASE 1: Junior Analyst — Access Control
    # Expected behavior: Deny access to restricted management data
    # ============================================================

    print("\n[CASE 1] Junior Analyst — Data Access Restriction")
    session_config_1 = {"configurable": {"thread_id": "soc_case_01"}}
    
    junior_input = {
        "messages": [HumanMessage(content="Query and display all records inside the Servers table where importance equals 'Management'.")],
        "analyst_role": "Junior"
    }
    
    # Execute workflow
    async for step_output in soc_application.astream(junior_input, session_config_1, stream_mode="values"):
        _print_new_messages(step_output)
    print("\n[INFO] Case 1 completed successfully.")
    # Expected outcome: Access to restricted data is denied.


    # ============================================================
    # CASE 2: Senior Analyst — Action Rejected
    # Expected behavior: Do not isolate the host after rejection
    # ============================================================

    print("\n\n[CASE 2] Senior Analyst — Isolation Rejected")
    
    session_config_2 = {
        "configurable": {"thread_id": "soc_case_02"}
    }
    senior_input = {
        "messages": [HumanMessage(content="Check system where ip is 192.168.1.90 inside the Servers table. If compromised, modify its database status to 'isolated' immediately.")],
        "analyst_role": "Senior"
    }
    
    # Execute workflow until human approval is required
    async for step_output in soc_application.astream(senior_input, session_config_2, stream_mode="values"):
        _print_new_messages(step_output)

    approval_attempts = 0
    current_state = await soc_application.aget_state(session_config_2)
    while current_state.next and approval_attempts < 4:   
        # Human intervention: Reject the requested action
        print("\n[HUMAN SIMULATION] Supervisor decision: REJECT")    
        
        async for step_output in soc_application.astream(Command(resume={"action": "reject"}), session_config_2, stream_mode="values"):
            _print_new_messages(step_output)
        approval_attempts += 1
        current_state = await soc_application.aget_state(session_config_2)
    
    if approval_attempts >= 4 and current_state.next:
        print("\n[SYSTEM NOTICE] Case 2: Terminated loop automatically due to persistent database schema errors.")
    else:
        print("\n[INFO] Case 2 completed successfully.")
    # Expected outcome: The host is not isolated.


    # ============================================================
    # CASE 3: Senior Analyst — Action Approved
    # Expected behavior: Fetch threat intelligence, then isolate host
    # ============================================================

    print("\n\n[CASE 3] Senior Analyst — Isolation Approved")

    session_config_3 = {
        "configurable": {"thread_id": "soc_case_03"}
    }    
    
    senior_input_approve = {
        "messages": [
            HumanMessage(content="First fetch threat intelligence for CVE-2026-0001 via MCP. Then immediately isolate the system where ip is 192.168.1.50 in the database.")
        ],
        "analyst_role": "Senior"
    }
    
    # Execute workflow until human approval is required
    async for step_output in soc_application.astream(senior_input_approve, session_config_3, stream_mode="values"):
        _print_new_messages(step_output)

    approval_attempts = 0
    current_state = await soc_application.aget_state(session_config_3)
    while current_state.next and approval_attempts < 4:           
        # Human intervention: Approve the requested action
        print("\n[HUMAN SIMULATION] Supervisor decision: APPROVE")

        async for step_output in soc_application.astream(Command(resume={"action": "approve"}), session_config_3, stream_mode="values"):
            _print_new_messages(step_output)
        approval_attempts += 1
        current_state = await soc_application.aget_state(session_config_3)

    if approval_attempts >= 4 and current_state.next:
        print("\n[SYSTEM NOTICE] Case 3: Terminated loop automatically due to persistent database schema errors.")
    else:
        print("\n[INFO] Case 3 completed successfully.")
    # Expected outcome: Threat intelligence is fetched and the isolation action proceeds after supervisor approval.

if __name__ == "__main__":
    asyncio.run(run_pipeline())